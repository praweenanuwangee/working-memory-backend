"""Measure uncompressed wheel contents without installing Linux packages on Windows."""
import sys
import zipfile
from pathlib import Path

wheels = list(Path(sys.argv[1]).glob('*.whl'))
if not wheels:
    raise SystemExit('No wheels found; this is not a completed bundle measurement')
total = 0
for wheel in wheels:
    with zipfile.ZipFile(wheel) as archive:
        size = sum(item.file_size for item in archive.infolist())
    total += size
    print(f'{wheel.name}: {size:,} bytes uncompressed')
print(f'Total wheel contents: {total:,} bytes ({total / 1024**2:.1f} MiB)')
print('Add the model, application, generated bytecode and runtime overhead for the final Vercel bundle.')
